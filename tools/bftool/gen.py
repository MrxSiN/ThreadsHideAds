"""Regenerates canonical `.bf`, the symbol map and the AOT C source.

Usage (from the repository root):

    python -m tools.bftool.gen            # regenerate
    python -m tools.bftool.gen --check    # fail when generated files are stale

Inputs:  brainfuck/programs.json, brainfuck/src/*.bfa
Outputs: brainfuck/generated/*.bf, brainfuck/generated/manifest.json,
         app/src/main/cpp/generated/bf_programs.generated.c
"""

import argparse
import hashlib
import json
import os
import sys

if __package__ in (None, ""):
    sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
    __package__ = "bftool"

from . import asm, ir  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
MANIFEST = os.path.join(ROOT, "brainfuck", "programs.json")
BF_DIR = os.path.join(ROOT, "brainfuck", "generated")
C_OUT = os.path.join(ROOT, "app", "src", "main", "cpp", "generated", "bf_programs.generated.c")
C_ABI = os.path.join(ROOT, "app", "src", "main", "cpp", "generated", "bf_abi.h")
JAVA_ABI = os.path.join(ROOT, "app", "src", "main", "java", "my", "github", "MrxSiN",
                        "threadshideads", "bridge", "BfAbi.java")
CONSTANTS = os.path.join(ROOT, "brainfuck", "src", "constants.bfa")


def abi_constants(path=CONSTANTS):
    a = asm.Assembler()
    a.assemble_file(path)
    return a.consts


def emit_abi(consts):
    names = list(consts)
    java = [
        "package my.github.MrxSiN.threadshideads.bridge;",
        "",
        "/** Generated by tools/bftool/gen.py from brainfuck/src/constants.bfa. Do not edit. */",
        "public final class BfAbi {",
        "",
        "    private BfAbi() {",
        "    }",
        "",
    ]
    java += ["    public static final int %s = %d;" % (n, consts[n]) for n in names]
    java += ["}", ""]
    c = [
        "/* Generated by tools/bftool/gen.py from brainfuck/src/constants.bfa. Do not edit. */",
        "#ifndef THREADSHIDEADS_BF_ABI_H",
        "#define THREADSHIDEADS_BF_ABI_H",
        "",
    ]
    c += ["#define BF_%s %d" % (n, consts[n]) for n in names]
    c += ["", "#endif", ""]
    return "\n".join(java), "\n".join(c)


def wrap(code, width=100):
    return "\n".join(code[i:i + width] for i in range(0, len(code), width)) + "\n"


def load_manifest(path=MANIFEST):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def generate(manifest_path=MANIFEST):
    """Returns {path: text} for every generated file."""
    manifest = load_manifest(manifest_path)
    base = os.path.dirname(manifest_path)
    files = {}
    c_parts = [
        "/* Generated by tools/bftool/gen.py from brainfuck/src. Do not edit. */",
        "#include \"../bf_runtime.h\"",
        "",
    ]
    table = []
    summary = {"programs": []}
    for index, entry in enumerate(manifest["programs"]):
        if entry["id"] != index:
            raise SystemExit("programs.json ids must be 0..n-1 in order")
        program, _ = asm.assemble(os.path.join(base, entry["source"]), entry["tape"],
                                  entry.get("persist", 0))
        if program.persist_size > entry.get("persist", 0):
            raise SystemExit("%s declares %d persistent cells, manifest allows %d"
                             % (entry["name"], program.persist_size, entry.get("persist", 0)))
        name = entry["name"]
        bf = wrap(program.code)
        files[os.path.join(BF_DIR, name + ".bf")] = bf
        ops = ir.compile_bf(program.code, zero_from=entry.get("persist", 0))
        if not ir.is_static(ops):
            raise SystemExit("%s: generated BF must keep every loop balanced" % name)
        c_parts.append(ir.emit_c(ops, name, entry["tape"]))
        table.append('    {"%s", bf_prog_%s, %d, %d},' % (name, name, entry["tape"], entry.get("persist", 0)))
        summary["programs"].append({
            "id": index,
            "name": name,
            "tape": entry["tape"],
            "persist": entry.get("persist", 0),
            "bf_sha256": hashlib.sha256(program.code.encode()).hexdigest(),
            "bf_commands": len(program.code),
            "ir_ops": ir.count_ops(ops),
            "dfa_states": program.dfas,
            "symbols": [{"region": r, "name": n, "addr": a, "size": s}
                        for r, n, a, s in program.symbols],
        })
    c_parts.append("const bf_program_info bf_programs[] = {")
    c_parts.extend(table)
    c_parts.append("};")
    c_parts.append("const int bf_program_count = %d;" % len(table))
    c_parts.append("")
    files[C_OUT] = "\n".join(c_parts)
    files[os.path.join(BF_DIR, "manifest.json")] = json.dumps(summary, indent=1, sort_keys=True) + "\n"
    if manifest_path == MANIFEST:
        files[JAVA_ABI], files[C_ABI] = emit_abi(abi_constants())
    return files


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    files = generate()
    stale = []
    for path, text in sorted(files.items()):
        current = None
        if os.path.exists(path):
            with open(path, encoding="utf-8", newline="") as f:
                current = f.read()
        if current != text:
            stale.append(os.path.relpath(path, ROOT))
            if not args.check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
    if args.check:
        if stale:
            print("Generated Brainfuck files are stale; run python tools/bftool/gen.py:")
            for p in stale:
                print("  " + p)
            return 1
        print("Generated Brainfuck files are up to date.")
        return 0
    for p in stale:
        print("wrote " + p)
    return 0


if __name__ == "__main__":
    sys.exit(main())
